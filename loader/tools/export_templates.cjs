#!/usr/bin/env node
// Export the modloader's prebuilt FS-call bridge templates as a Lua data file for s2_ml.
// For each template (call0..call6, allocate, publish) it emits the .text bytes with the
// literals zeroed and the original_tail branch immediate zeroed, the branch position, and the
// literal offsets. Lua then fills owner/operation/result/args and the branch for a given cave.
//   node tools/export_templates.cjs <ns2jb-modloader-source> <out.lua>
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const [src, out] = process.argv.slice(2);
const {textSection} = require(path.join(path.resolve(src), 'lib/native/elf-text.cjs'));
const t = JSON.parse(fs.readFileSync(path.join(src, 'native/prebuilt/templates.json'), 'utf8'));
const names = ['call0', 'call1', 'call2', 'call3', 'call4', 'call5', 'call6', 'allocate', 'publish'];
const rows = [];
for (const name of names) {
  const row = t[name];
  const elf = Buffer.from(row.object, 'base64');
  const a = textSection(elf, 0n, {original_tail: 0x100000n});
  const b = textSection(elf, 0n, {original_tail: 0x200000n});
  const diffs = [];
  for (let i = 0; i < a.length; i += 4) if (a.readUInt32LE(i) !== b.readUInt32LE(i)) diffs.push(i);
  if (diffs.length !== 1) throw Error(name + ': expected one relocated branch, found ' + diffs.length);
  const pos = diffs[0];
  const word = a.readUInt32LE(pos);
  if ((word & 0xfc000000) !== 0x14000000) throw Error(name + ': relocated word is not B');
  const code = Buffer.from(a);
  code.writeUInt32LE(0x14000000, pos);                 // imm filled in on the console
  const lit = {};
  for (const s of ['owner', 'operation', 'result', 'arg0', 'arg1', 'arg2', 'arg3', 'arg4', 'arg5']) {
    if (row.symbols[s]) {
      lit[s] = row.symbols[s].value;
      if (!code.subarray(lit[s], lit[s] + 8).equals(Buffer.alloc(8))) throw Error(name + ': literal ' + s + ' not zero');
    }
  }
  if (code.length > 256) throw Error(name + ' exceeds 256 bytes');
  rows.push({name, hex: code.toString('hex'), branch: pos, lit, size: code.length});
}
const lua = ['-- generated by tools/export_templates.cjs from ns2jb-modloader native/prebuilt/templates.json',
  'return {'];
for (const r of rows) {
  const lits = Object.entries(r.lit).map(([k, v]) => `${k}=${v}`).join(', ');
  lua.push(`  ${r.name} = {hex = "${r.hex}", branch = ${r.branch}, size = ${r.size}, lit = {${lits}}},`);
}
lua.push('}', '');
fs.writeFileSync(out, lua.join('\n'));
console.log(rows.map(r => `${r.name}: ${r.size} B, branch @${r.branch}, literals ${Object.keys(r.lit).join(',')}`).join('\n'));
